#!/usr/bin/env python3
"""Render a conservative HAProxy HTTP Host/path router for TCP port 80.

This is a generator only: it does not write system files or alter services.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
LABEL_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?$")
PATH_RE = re.compile(r"^/[A-Za-z0-9._~!$&'()*+,;=:@%/-]*$")


class ConfigError(ValueError):
    pass


def valid_hostname(value: Any) -> bool:
    return (
        isinstance(value, str) and bool(value) and len(value) <= 253
        and all(1 <= len(label) <= 63 and LABEL_RE.fullmatch(label)
                for label in value.split("."))
    )


def validate_manifest(data: Any) -> list[dict[str, Any]]:
    if not isinstance(data, dict) or set(data) != {"routes"}:
        raise ConfigError("manifest must contain only a 'routes' array")
    if not isinstance(data["routes"], list) or not data["routes"]:
        raise ConfigError("'routes' must be a non-empty array")
    output: list[dict[str, Any]] = []
    names: set[str] = set()
    matchers: set[tuple[str, str]] = set()
    for index, route in enumerate(data["routes"]):
        if not isinstance(route, dict):
            raise ConfigError(f"route {index + 1} must be an object")
        if set(route) not in (
            {"name", "host", "backend_host", "backend_port"},
            {"name", "host", "path_prefix", "backend_host", "backend_port"},
        ):
            raise ConfigError(f"route {index + 1} has missing or unknown fields")
        name, host = route["name"], route["host"]
        path = route.get("path_prefix", "")
        backend, port = route["backend_host"], route["backend_port"]
        if not isinstance(name, str) or not NAME_RE.fullmatch(name) or name in names:
            raise ConfigError(f"route {index + 1}: invalid or duplicate route name")
        if not valid_hostname(host):
            raise ConfigError(f"route {name}: invalid HTTP Host hostname")
        if not isinstance(path, str) or (path and not PATH_RE.fullmatch(path)):
            raise ConfigError(f"route {name}: invalid path_prefix")
        matcher = (host.lower(), path)
        if matcher in matchers:
            raise ConfigError(f"route {name}: duplicate Host/path matcher")
        if backend not in ("127.0.0.1", "::1"):
            raise ConfigError(f"route {name}: backend must be loopback-only")
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            raise ConfigError(f"route {name}: backend_port must be an integer from 1 to 65535")
        names.add(name)
        matchers.add(matcher)
        output.append({
            "name": name, "host": host, "path_prefix": path,
            "backend_host": backend, "backend_port": port,
        })
    return sorted(output, key=lambda item: (-len(item["path_prefix"]), item["name"]))


def render(routes: list[dict[str, Any]]) -> str:
    lines = [
        "# Generated by Africhome; review before any manual deployment.",
        "# Plain HTTP Host/path routing only; not an SSH payload/proxy gateway.",
        "global",
        "    log /dev/log local0",
        "    maxconn 4096",
        "",
        "defaults",
        "    log global",
        "    mode http",
        "    option httplog",
        "    timeout connect 5s",
        "    timeout client  1m",
        "    timeout server  1m",
        "    timeout tunnel  1h",
        "",
        "frontend africhome_http_80",
        "    bind 0.0.0.0:80",
        "    mode http",
    ]
    for route in routes:
        lines.append(
            f"    acl host_{route['name']} hdr(host),lower,field(1,:) -m str {route['host'].lower()}"
        )
        conditions = [f"host_{route['name']}"]
        if route["path_prefix"]:
            lines.append(
                f"    acl path_{route['name']} path_beg -i {route['path_prefix']}"
            )
            conditions.append(f"path_{route['name']}")
        lines.append(
            f"    use_backend be_{route['name']} if {' '.join(conditions)}"
        )
    lines.extend(["    default_backend be_unmatched", ""])
    for route in routes:
        backend = (
            f"[{route['backend_host']}]"
            if route["backend_host"] == "::1"
            else route["backend_host"]
        )
        lines.extend([
            f"backend be_{route['name']}",
            "    mode http",
            f"    server srv_{route['name']} {backend}:{route['backend_port']} check",
            "",
        ])
    lines.extend([
        "backend be_unmatched",
        "    mode http",
        "    http-request deny deny_status 421",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"Usage: {Path(argv[0]).name} ROUTES.json", file=sys.stderr)
        return 2
    try:
        with open(argv[1], "r", encoding="utf-8") as handle:
            routes = validate_manifest(json.load(handle))
        sys.stdout.write(render(routes))
    except (OSError, json.JSONDecodeError, ConfigError) as exc:
        print(f"http-router-render: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
