#!/usr/bin/env python3
"""Render a conservative HAProxy TCP/SNI passthrough config.

This tool only renders text to stdout. It never writes system files, binds ports,
installs packages, changes firewall rules, or restarts services.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
LABEL_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?$")


class ConfigError(ValueError):
    pass


def valid_hostname(value: Any) -> bool:
    if not isinstance(value, str) or not value or len(value) > 253:
        return False
    return all(
        1 <= len(label) <= 63 and LABEL_RE.fullmatch(label) is not None
        for label in value.split(".")
    )


def validate_manifest(data: Any) -> list[dict[str, Any]]:
    if not isinstance(data, dict) or set(data) != {"routes"}:
        raise ConfigError("manifest must contain only a 'routes' array")
    routes = data["routes"]
    if not isinstance(routes, list) or not routes:
        raise ConfigError("'routes' must be a non-empty array")

    validated: list[dict[str, Any]] = []
    names: set[str] = set()
    snis: set[str] = set()
    for index, route in enumerate(routes):
        if not isinstance(route, dict) or set(route) != {
            "name", "sni", "backend_host", "backend_port"
        }:
            raise ConfigError(f"route {index + 1} has missing or unknown fields")
        name, sni, host, port = (
            route["name"], route["sni"], route["backend_host"], route["backend_port"]
        )
        if not isinstance(name, str) or not NAME_RE.fullmatch(name):
            raise ConfigError(f"route {index + 1}: invalid route name")
        if name in names:
            raise ConfigError(f"duplicate route name: {name}")
        if not valid_hostname(sni):
            raise ConfigError(f"route {name}: invalid SNI hostname")
        if sni.lower() in snis:
            raise ConfigError(f"duplicate SNI hostname: {sni}")
        if host not in ("127.0.0.1", "::1"):
            raise ConfigError(f"route {name}: backend must be loopback-only")
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            raise ConfigError(f"route {name}: backend_port must be an integer from 1 to 65535")
        names.add(name)
        snis.add(sni.lower())
        validated.append({
            "name": name, "sni": sni, "backend_host": host, "backend_port": port
        })
    return validated


def render(routes: list[dict[str, Any]]) -> str:
    lines = [
        "# Generated by Africhome; review before any manual deployment.",
        "# TCP/TLS passthrough only. This does not terminate TLS or handle SSH payloads.",
        "global",
        "    log /dev/log local0",
        "    maxconn 4096",
        "",
        "defaults",
        "    log global",
        "    mode tcp",
        "    option tcplog",
        "    timeout connect 5s",
        "    timeout client  1m",
        "    timeout server  1m",
        "",
        "frontend africhome_tls_443",
        "    bind 0.0.0.0:443",
        "    mode tcp",
        "    tcp-request inspect-delay 5s",
        "    tcp-request content accept if { req.ssl_hello_type 1 }",
    ]
    for route in routes:
        lines.append(f"    acl sni_{route['name']} req.ssl_sni -i {route['sni']}")
        lines.append(f"    use_backend be_{route['name']} if sni_{route['name']}")
    lines.extend(["    default_backend be_unmatched", ""])
    for route in routes:
        lines.extend([
            f"backend be_{route['name']}",
            "    mode tcp",
            f"    server srv_{route['name']} {route['backend_host']}:{route['backend_port']} check",
            "",
        ])
    lines.extend([
        "backend be_unmatched",
        "    mode tcp",
        "    tcp-request content reject",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"Usage: {Path(argv[0]).name} ROUTES.json", file=sys.stderr)
        return 2
    try:
        with open(argv[1], "r", encoding="utf-8") as handle:
            data = json.load(handle)
        sys.stdout.write(render(validate_manifest(data)))
    except (OSError, json.JSONDecodeError, ConfigError) as exc:
        print(f"central-router-render: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
